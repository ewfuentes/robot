"""Collate the triage outputs of a dataset collection into one markdown table.

The three triage tools each write their own answer into
`pipeline_metadata.json` (`mount_offset`, `recording_seams`) or a manifest
(`vehicle_anchor.json`), and the useful judgements only appear when they are read
side by side: a `rigid` anchor beside a high axis MAD means the estimator failed
on a fixed camera, which is a method gap, while `drifting` beside the same MAD
means the camera really moved. This writes that joined view so nobody has to
open fourteen JSON files to get it.

    bazel run //experimental/overhead_matching/swag/scripts:dataset_status_table -- \
        --base /data/farfield_matching/mapillary_datasets
"""

import argparse
import csv
import json
from pathlib import Path

HEADER = ("| dataset | proj | frames | km | trim | offset | axis MAD | rev | "
          "pairs | survives mask | self-consistent | anchor | seams | worst m/s |")
PREAMBLE = """# Dataset triage status

Generated by `dataset_status_table.py`. Every column is read back from the
datasets themselves, so regenerating after any change is the way to refresh it.

**No `mount_offset_deg` here is accuracy-validated.** The gates behind
`self-consistent` test whether the per-pair estimates agree with each other,
which is precision. `boston_harbor_leg1` reports axis MAD 2.0 deg while sitting
14 deg off its triangulation-verified 214 deg and selecting the opposite
direction of the axis, so a passing gate is not a correct angle. Treat these as
triage — "does this leg have a fixed mount at all?" — and get calibrations from a
triangulation-residual sweep.

**`survives mask` is the strongest per-dataset evidence available**, because it
needs no external reference: re-fit with the vehicle's own structure masked out
and see whether the angle holds. A fit driven by real scene motion barely moves;
one that was fitting the boat collapses. `no` means the unmasked number is an
artefact of zero-parallax structure bolted to the camera.

The convention throughout: `mount_offset_deg` is the azimuth **in the camera
frame of the direction of travel**, not the bow.
"""


def collect(base: Path):
    anchor_path = base / "_manifests" / "vehicle_anchor.json"
    anchor = {}
    if anchor_path.exists():
        anchor = {d["dataset"]: d for d in json.loads(anchor_path.read_text())}
    rows = []
    for meta_path in sorted(base.glob("*/pipeline_metadata.json")):
        ds = meta_path.parent
        meta = json.loads(meta_path.read_text())
        gps = list(csv.DictReader(open(ds / "frames_gps.csv")))
        mo = meta.get("mount_offset") or {}
        seams = meta.get("recording_seams", {})
        worst = max([s.get("implied_speed_mps") or 0.0
                     for s in seams.get("seams", [])], default=0.0)
        rows.append({
            "name": ds.name,
            "proj": meta.get("projection", "?")[:5],
            "n": meta.get("num_images", len(gps)),
            "km": float(gps[-1]["dist_m"]) / 1000.0 if gps else 0.0,
            "trims": len(meta.get("trims", [])),
            "off": mo.get("mount_offset_deg"),
            "mad": mo.get("axis_mad_deg"),
            "rev": mo.get("reversal_fraction"),
            "pairs": mo.get("pairs_used"),
            "survives": mo.get("survives_vehicle_mask"),
            "consistent": mo.get("self_consistent"),
            "anchor": anchor.get(ds.name, {}).get("verdict", "—"),
            "seams": seams.get("n_seams", 0),
            "worst": worst,
        })
    return rows


def render(rows):
    def num(value, spec, suffix=""):
        return "—" if value is None else format(value, spec) + suffix

    def flag(value):
        return {None: "—", True: "yes", False: "**no**"}[value]

    lines = [HEADER, "|" + "---|" * 14]
    for r in sorted(rows, key=lambda x: (x["survives"] is False,
                                         not x["consistent"],
                                         x["mad"] if x["mad"] is not None else 999)):
        lines.append(
            f"| `{r['name']}` | {r['proj']} | {r['n']} | {r['km']:.1f} | "
            f"{r['trims']} | {num(r['off'], '.1f', '°')} | "
            f"{num(r['mad'], '.1f', '°')} | "
            f"{num(r['rev'] * 100 if r['rev'] is not None else None, '.0f', '%')} | "
            f"{r['pairs'] if r['pairs'] is not None else '—'} | "
            f"{flag(r['survives'])} | {flag(r['consistent'])} | {r['anchor']} | "
            f"{r['seams']} | {r['worst']:.0f} |")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base", type=Path, required=True)
    p.add_argument("--output", type=Path, default=None,
                   help="default: <base>/_manifests/STATUS.md")
    args = p.parse_args()

    rows = collect(args.base)
    table = render(rows)
    out = args.output or (args.base / "_manifests" / "STATUS.md")
    out.write_text(PREAMBLE + "\n" + table + "\n")
    print(table)
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
