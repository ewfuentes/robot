class HealthRecord(msgspec.Struct):
    """Tier-0 health scalars, one per keyframe (design doc §5.6/§7.1).

    All belief statistics describe the WEIGHTED posterior at this keyframe,
    before any resampling or roughening. `resampled` reports whether a
    resample was triggered by this keyframe's ESS, i.e. it acts on the state
    carried into the next keyframe.
    """
    keyframe_idx: int
    ess: float
    resampled: bool
    mean_east_m: float
    mean_north_m: float
    mean_heading_deg: float
    map_east_m: float
    map_north_m: float
    map_heading_deg: float
    position_std_m: float
    heading_std_deg: float
    n_measurements: int
    # Weight held by particles that came from some proposal event; 0 when
    # the belief is entirely motion-model descended.
    proposal_weight_share: float = 0.0
    proposal_event_id: int | None = None  # set on keyframes that fired
    associations: list[AssociationPosterior] = []
    modes: list[ModeRecord] = []
    # Shannon entropy of the mode weights, in nats: 0 when the belief is
    # effectively unimodal, log(k) when k modes share the mass equally.
    mode_entropy_nats: float = 0.0
    # Fully keyed posterior masses centered on the true position, from
    # RunManifest.position_mass_metric. Populated by the evaluation-only
    # observer at every keyframe when truth is available; empty otherwise.
    position_probability_mass: dict[str, float] = {}


class ProposalEvent(msgspec.Struct):
    """A fired proposal, logged for the run's event index (§7.3).

    Carries the provenance every injected particle points back to, so the
    viewer can answer "where did this mode come from" (§5.5 [CONTRACT]).
    """
    event_id: int
    keyframe_idx: int
    trigger: str  # "init" | "null_share" | "ess_floor"
    n_hypotheses: int
    n_injected: int
    n_tracklets_considered: int
    n_combinations_examined: int
    n_combinations_skipped: int
    particle_budget: int = 0
    n_combinations_total: int = 0
    n_combinations_enumerated: int = 0
    n_combinations_sampled: int = 0
    n_combinations_geometry_pruned: int = 0
    n_partially_represented_ties: int = 0
    n_solution_clusters_merged: int = 0
    represented_compatibility_mass: float = 0.0
    # Evidence gate (§5.5): a rejected event has n_injected 0 and
    # gate_passed False. Scores are window log-likelihoods in nats.
    gate_passed: bool = True
    gate_best_hypothesis_nats: float | None = None
    gate_reference_nats: float | None = None
    # Parallel to the hypothesis index recorded on each injected particle.
    hypothesis_tracklet_ids: list[list[str]] = []
    hypothesis_landmark_ids: list[list[str]] = []


class TruthPose(msgspec.Struct):
    """Ground-truth position plus recorded GPS/trajectory course.

    Course is diagnostic truth only. It is not a measured platform heading
    or fixed nominal-forward orientation, and the filter never reads it.
    """
    keyframe_idx: int
    east_m: float
    north_m: float
    course_world_cw_deg: float


class RunManifest(msgspec.Struct):
    """The run's own record: config echo, provenance, replay surface.

    Required provenance includes:
      - max_visible_range_m: the catalog visibility radius this run was
        built with, which shapes proposal hypotheses;
      - export_dir: where the inputs came from. Synthetic runs record
        "synthetic:<scenario>" explicitly;
      - git_commit / argv / created: who made this, how, when.
    """
    schema_version: str
    dataset: str
    scenario_name: str
    run_kind: str
    initialization_kind: str
    bearings_consumed: bool
    proposal_enabled: bool
    localization_inputs_manifest_sha256: str | None
    anchor_lat_deg: float
    anchor_lon_deg: float
    n_keyframes: int
    filter_config: FilterConfig
    landmarks: list[LandmarkEntry]
    matcher_version: str
    max_visible_range_m: float
    export_dir: str
    git_commit: str
    argv: list[str]
    created: str
    particle_history_sha256: str = ""
    # Explicit control classification. These tags identify ablations without
    # overloading matcher_version, which must continue to identify table bytes.
    ablation_tags: list[str] = []
    # Truth is optional. When present, schema identifies truth.jsonl and the
    # optional artifact mapping identifies its immutable external source.
    truth_position_artifact: dict[str, str] | None = None
    truth_position_schema: str | None = None
    # Resolved truth-centered primary-metric identity/config. None when no
    # truth is present. The default headline radius is 500 m.
    position_mass_metric: PositionMassMetricConfig | None = None
    # Retrieval observation source (schema 0.8): consumed iff the run's
    # filter multiplied retrieval score fields into the belief; the source
    # directory names where the fields came from. The consumed fields are
    # copied into the run artifact as replay surface.
    retrieval_consumed: bool = False
    retrieval_dir: str | None = None
